"""Markdown Report exporter rendering GFM with tables and query citations."""

from typing import Any


class MarkdownReportExporter:
    """Renders structured GitHub-Flavored Markdown reports with embedded tables."""

    def render_markdown(self, report_data: dict[str, Any]) -> str:
        """Convert report dictionary into comprehensive Markdown."""
        title = report_data.get("title", "Lumen Executive Report")
        generated_at = report_data.get("generated_at", "N/A")
        dataset_name = report_data.get("dataset_name", "Enterprise Dataset")
        exec_summary = report_data.get("executive_summary", "")

        md_lines = [
            f"# {title}",
            "",
            f"> **Generated by Lumen AI Data Analyst** | Date: `{generated_at}` | Dataset: `{dataset_name}`",
            "",
            "## Executive Summary",
            "",
            exec_summary,
            "",
            "## Data Health & Quality Audit",
            "",
        ]

        data_health = report_data.get("data_health", {})
        if data_health:
            md_lines.extend([
                "| Metric | Audit Value | Status |",
                "| :--- | :--- | :--- |",
                f"| **Overall Health Score** | `{data_health.get('score', 100)}/100` | Excellent |",
                f"| **Rows Audited** | `{data_health.get('rows_audited', 0):,}` | Verified |",
                f"| **Integrity Checks Passed** | `{data_health.get('integrity_checks_passed', 0)}` | Confirmed |",
                "",
            ])

        md_lines.extend([
            "## Key Analytical Findings",
            "",
        ])

        findings = report_data.get("findings", [])
        for i, f in enumerate(findings, 1):
            conf = f.get("confidence", "High")
            md_lines.extend([
                f"### Finding {i} (Confidence: {conf})",
                "",
                f"{f.get('full_text', f.get('summary', ''))}",
                "",
            ])

        md_lines.extend([
            "## Verified Evidence Ledger & Executed Queries",
            "",
            "The following SQL queries were executed in the analytical engine and verified by the skeptic auditor:",
            "",
        ])

        queries = report_data.get("sql_queries", [])
        if queries:
            for q in queries:
                q_text = q.get("query", "").strip()
                runtime = q.get("runtime_ms", 0.0)
                rows = q.get("row_count", 0)
                md_lines.extend([
                    "```sql",
                    q_text,
                    "```",
                    f"*Execution time: `{runtime:.1f}ms` | Rows returned: `{rows}`*",
                    "",
                ])
        else:
            md_lines.append("*No SQL queries recorded in this session.*")

        charts = report_data.get("charts", [])
        if charts:
            md_lines.extend(["## Generated Charts", ""])
            for chart in charts:
                chart_data = chart.get("data", {})
                labels = chart_data.get("x_axis") or [item.get("name") for item in chart_data.get("slices", [])]
                values = chart_data.get("series") or [item.get("value") for item in chart_data.get("slices", [])]
                md_lines.extend([f"### {chart.get('title', 'Chart')}", ""])
                if labels and len(labels) == len(values):
                    md_lines.extend(["| Category | Computed value |", "| :--- | ---: |"])
                    md_lines.extend(f"| {label} | {value} |" for label, value in zip(labels, values, strict=True))
                    md_lines.append("")

        md_lines.extend([
            "## Anomaly & Risk Analysis",
            "",
        ])
        anomalies = report_data.get("anomalies", [])
        for a in anomalies:
            md_lines.append(f"- **Flagged Item**: {a.get('finding', '')}")
        md_lines.append("")

        verifier_audit = report_data.get("verifier_audit", {})
        if verifier_audit:
            md_lines.extend([
                "## Skeptic Verifier Audit Trail",
                "",
                f"- **Cross-Method Parity**: {verifier_audit.get('cross_method_check', 'Verified')}",
                f"- **Numerical Grounding**: {verifier_audit.get('number_grounding', '100% grounded')}",
                f"- **Join Fan-Out Risk**: {verifier_audit.get('join_fanout_risk', 'Low')}",
                "",
            ])

        md_lines.extend([
            "---",
            "*Report produced autonomously by Lumen — Trust Engineered Analytics.*",
        ])

        return "\n".join(md_lines)
