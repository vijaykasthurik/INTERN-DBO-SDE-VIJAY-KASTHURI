"""PDF Report exporter using ReportLab and Matplotlib chart figures."""

import os
import tempfile
import threading
from pathlib import Path
from typing import Any
from xml.sax.saxutils import escape

import matplotlib

matplotlib.use("Agg")  # Non-interactive headless backend
import matplotlib.pyplot as plt
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (
    Flowable,
    HRFlowable,
    Image,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)


class Wordmark(Flowable):
    """Use the same vector letterforms as the application, with searchable text."""
    def __init__(self) -> None:
        super().__init__()
        self.width,self.height = 112,28

    def draw(self) -> None:
        from reportlab.graphics import renderPDF
        from svglib.svglib import svg2rlg
        source = Path(__file__).resolve().parent / "wordmark.svg"
        if not source.exists():
            source = Path(__file__).resolve().parents[3] / "frontend" / "public" / "wordmark.svg"
        if not source.exists():
            source = Path("/app/assets/wordmark.svg")
        drawing = None
        if source.exists():
            try:
                drawing = svg2rlg(str(source))
            except Exception:
                drawing = None
        svg_width = float(getattr(drawing, "width", 0.0)) if drawing is not None else 0.0
        if drawing is not None and svg_width > 0:
            scale = self.width / svg_width
            drawing.scale(scale, scale)
            renderPDF.draw(drawing, self.canv, 0, 0)
        else:
            self.canv.setFont("Helvetica-Bold", 16)
            self.canv.setFillColor(colors.HexColor("#0B0B0F"))
            self.canv.drawString(0, 8, "Lumen")
        text = self.canv.beginText(0, 0)
        text.setTextRenderMode(3)
        text.setFont("Helvetica", 10)
        text.textLine("Lumen")
        self.canv.drawText(text)


class PDFReportExporter:
    """Renders professional white/minimalist PDF reports matching the Lumen design system."""

    _render_lock = threading.Lock()

    def render_pdf(self, report_data: dict[str, Any], output_path: str) -> str:
        with self._render_lock:
            return self._render_pdf(report_data,output_path)

    def _render_pdf(self, report_data: dict[str, Any], output_path: str) -> str:
        """Compile PDF document to file with embedded Matplotlib analytical visualizations."""
        doc = SimpleDocTemplate(
            output_path,
            pagesize=letter,
            rightMargin=54,
            leftMargin=54,
            topMargin=54,
            bottomMargin=54,
        )

        styles = getSampleStyleSheet()

        # Custom Lumen Design System Typography Styles
        title_style = ParagraphStyle(
            "LumenTitle",
            parent=styles["Heading1"],
            fontSize=22,
            leading=26,
            textColor=colors.HexColor("#0B0B0F"),
            fontName="Helvetica-Bold",
            spaceAfter=4,
        )
        subtitle_style = ParagraphStyle(
            "LumenSubtitle",
            parent=styles["Normal"],
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#64748B"),
            fontName="Helvetica",
            spaceAfter=14,
        )
        heading_style = ParagraphStyle(
            "LumenH2",
            parent=styles["Heading2"],
            fontSize=13,
            leading=16,
            textColor=colors.HexColor("#0F172A"),
            fontName="Helvetica-Bold",
            spaceBefore=12,
            spaceAfter=6,
        )
        body_style = ParagraphStyle(
            "LumenBody",
            parent=styles["Normal"],
            fontSize=9.5,
            leading=13.5,
            textColor=colors.HexColor("#334155"),
            fontName="Helvetica",
            spaceAfter=8,
        )
        code_style = ParagraphStyle(
            "LumenCode",
            parent=styles["Code"],
            fontSize=8,
            leading=10.5,
            textColor=colors.HexColor("#1E293B"),
            fontName="Courier",
            backColor=colors.HexColor("#F8FAFC"),
            borderPadding=6,
            spaceAfter=6,
        )

        story = [Wordmark(),Spacer(1,12)]

        # 1. Header & Title
        title_text = escape(str(report_data.get("title", "Lumen Executive Report")))
        story.append(Paragraph(title_text, title_style))

        date_str = report_data.get("generated_at", "N/A")
        ds_name = report_data.get("dataset_name", "Enterprise Dataset")
        story.append(
            Paragraph(
                escape(f"Generated by Lumen Autonomous Data Analyst | Date: {date_str} | Dataset: {ds_name}"),
                subtitle_style,
            )
        )
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#E2E8F0"), spaceAfter=12))

        # 2. Executive Summary
        story.append(Paragraph("Executive Summary", heading_style))
        story.append(Paragraph(escape(str(report_data.get("executive_summary", ""))), body_style))
        story.append(Spacer(1, 8))

        # 3. Data Health Summary Table
        dh = report_data.get("data_health")
        if dh:
            story.append(Paragraph("Data Health & Integrity Audit", heading_style))
            health_data = [["Metric", "Audit Value"], ["Overall Data Health Score", f"{dh['score']} / 100"], ["Total Rows Audited", f"{dh['rows_audited']:,}"]]
            health_table = Table(health_data, colWidths=[250, 250])
            health_table.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F1F5F9")), ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0"))]))
            story.extend([health_table, Spacer(1, 14)])

        # 4. Render Matplotlib Chart & Embed
        chart_files: list[str] = []
        for chart in report_data.get("charts", []):
            data = chart.get("data", {})
            labels = data.get("x_axis") or [item.get("name") for item in data.get("slices", [])]
            values = data.get("series") or [item.get("value") for item in data.get("slices", [])]
            if not labels or not values or len(labels) != len(values):
                continue
            fig, ax = plt.subplots(figsize=(6.5, 2.8), dpi=150)
            ax.bar([str(label) for label in labels], [float(value) for value in values], color="#6366F1", width=0.55)
            ax.set_title(escape(str(chart.get("title", "Verified result"))), fontsize=10, fontweight="bold", color="#0F172A")
            ax.tick_params(axis="both", labelsize=8, colors="#475569")
            ax.spines["top"].set_visible(False)
            ax.spines["right"].set_visible(False)
            fig.tight_layout()
            temp_fd, chart_file = tempfile.mkstemp(suffix=".png")
            os.close(temp_fd)
            chart_files.append(chart_file)
            fig.savefig(chart_file, format="png")
            plt.close(fig)
            story.extend([Paragraph(escape(str(chart.get("title", "Verified result"))), heading_style), Image(chart_file, width=6.5 * inch, height=2.8 * inch), Spacer(1, 10)])

        # 5. Key Findings
        story.append(Paragraph("Analytical Findings", heading_style))
        for i, f in enumerate(report_data.get("findings", []), 1):
            txt = f.get("full_text", f.get("summary", ""))
            confidence = escape(str(f.get("confidence", "Unknown")))
            verification = "verified" if f.get("verified") else "not verifier-verified"
            story.append(Paragraph(f"<b>Finding {i} (Confidence: {confidence}; {verification}):</b> {escape(str(txt))}", body_style))
        story.append(Spacer(1, 8))

        # 6. SQL Evidence Ledger
        story.append(Paragraph("Evidence Ledger: Executed Queries", heading_style))
        for q in report_data.get("sql_queries", []):
            code_text = q.get("query", "").replace("\n", " ").strip()
            runtime = q.get("runtime_ms")
            rows = q.get("row_count")
            story.append(Paragraph(escape(code_text), code_style))
            latency = f"{runtime:.1f}ms" if runtime is not None else "not individually measured"
            story.append(Paragraph(f"<i>Execution latency: {latency} | Rows returned: {rows if rows is not None else 'not recorded'}</i>", subtitle_style))

        # 7. Verifier Skeptic Notes
        story.append(Paragraph("Skeptic Verifier Audit Trail", heading_style))
        va = report_data.get("verifier_audit", {})
        story.append(
            Paragraph(
                f"Numerical Grounding: {escape(str(va.get('number_grounding', 'Not available')))}<br/>"
                f"Cross-Check Method: {escape(str(va.get('cross_method_check', 'Not available')))}<br/>"
                f"Join Fan-Out Risk: {escape(str(va.get('join_fanout_risk', 'Not available')))}",
                body_style,
            )
        )

        def footer(canvas: Any, document: Any) -> None:
            canvas.saveState()
            canvas.setFont("Helvetica",8)
            canvas.setFillColor(colors.HexColor("#64748B"))
            canvas.drawRightString(letter[0]-54,32,f"Lumen | Page {document.page}")
            canvas.restoreState()
        try:
            doc.build(story,onFirstPage=footer,onLaterPages=footer)
        finally:
            for chart_file in chart_files:
                Path(chart_file).unlink(missing_ok=True)

        return output_path
